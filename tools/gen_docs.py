class DocsError(Exception):
    """Missing or inconsistent documentation data (exit 2)."""


def _yaml(path: Path) -> dict[str, Any]:
    data = load_yaml(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise DocsError(f"{path.name} must be a mapping")
    return data


def builtin_packs() -> list[LoadedRulepack]:
    folder = resources.files("neurogrid.rulepacks")
    return [load_rulepack(folder.joinpath(f"{name}.yaml").read_bytes(), "builtin") for name in PACKS]


def _value(value: object) -> str:
    return json.dumps(value, ensure_ascii=False) if isinstance(value, str) else str(value)


@dataclass(frozen=True)
class Context:
    lang: str
    labels: Mapping[str, Any]
    checks: Mapping[str, Mapping[str, str]]
    texts: Mapping[str, str]

    def t(self, key: str) -> str:
        if key not in self.texts:
            raise DocsError(f"missing language table key {self.lang}:{key}")
        return self.texts[key]


def context(lang: str) -> Context:
    return Context(
        lang=lang,
        labels=_yaml(DATA / f"labels.{lang}.yaml"),
        checks=_yaml(DATA / f"checks.{lang}.yaml"),
        texts=tables()[lang],
    )


def passes_text(check_id: str, spec: CheckSpec, ctx: Context) -> str:
    """The comparison a check declares (A-13): a bound, 'no deviation', evidence, or the documented rule."""
    labels = ctx.labels["checks"]
    if isinstance(spec.evaluate, Bound):
        key = "bound_max" if spec.evaluate.op == "<=" else "bound_min"
        return str(labels[key]).format(param=spec.evaluate.param)
    if check_id == EVIDENCE_CHECK:
        return str(labels["evidence"])
    if spec.evaluate is is_true:
        return str(labels["is_true"])
    documented = ctx.checks.get(check_id, {}).get("passes")
    if not documented:
        raise DocsError(
            f"{ctx.lang}: check {check_id} has an own comparison but no 'passes' text in docs/_data"
        )
    return str(documented)


def render_checks(ctx: Context, env: Environment) -> str:
    labels = ctx.labels["checks"]
    used: dict[str, list[str]] = {}
    for loaded in builtin_packs():
        # a placeholder rule is not evaluated: its ID carries the marker " (placeholder)" (A-41, A-92)
        placeholder = loaded.pack.source_status is SourceStatus.PLACEHOLDER
        suffix = str(ctx.labels["rules"]["placeholder_suffix"]) if placeholder else ""
        for rule in loaded.pack.rules:
            used.setdefault(rule.check, []).append(f"[{rule.id}](rules.md#{rule.id}){suffix}")
    rows = []
    for check_id in sorted(REGISTRY):
        spec = REGISTRY[check_id]
        entry = ctx.checks.get(check_id)
        if entry is None or not entry.get("object"):
            raise DocsError(f"{ctx.lang}: check {check_id} has no entry in docs/_data/checks.{ctx.lang}.yaml")
        params = [
            str(labels["kind"]).format(name=f"`{name}`", kind=p.kind, default=_value(p.default))
            for name, p in sorted(spec.params.items())
        ]
        rules = used.get(check_id, [])
        rows.append(
            {
                "id": check_id,
                "title": ctx.t(f"check.{check_id}"),
                "params": "; ".join(params) or labels["none"],
                "passes": passes_text(check_id, spec, ctx),
                "object": entry["object"],
                "rules": ", ".join(rules) or labels["none"],
            }
        )
    return env.get_template("checks.md.j2").render(L=labels, checks=rows)


def _params(rule_params: Mapping[str, object], spec: CheckSpec, labels: Mapping[str, Any]) -> str:
    parts = []
    for name, param in sorted(spec.params.items()):
        if name in rule_params:
            parts.append(str(labels["pack_param"]).format(name=f"`{name}`", value=_value(rule_params[name])))
        else:
            parts.append(str(labels["default_param"]).format(name=f"`{name}`", value=_value(param.default)))
    return "; ".join(parts) or str(labels["none"])


def render_rules(ctx: Context, env: Environment) -> str:
    labels = ctx.labels["rules"]
    packs = []
    for loaded in builtin_packs():
        pack = loaded.pack
        rules = []
        for rule in pack.rules:
            if pack.rulepack == "core":
                clause = f"[{rule.clause}](../metrics.md#{rule.clause})"
            elif pack.source_status is SourceStatus.PLACEHOLDER:
                clause = ctx.t("report.value.placeholder_clause")  # the report's wording (A-41)
            elif rule.clause == "unknown":
                clause = ctx.t("report.value.clause_unknown")
            else:
                clause = rule.clause
            strict = rule.strict_severity or rule.severity
            rules.append(
                {
                    "id": rule.id,
                    "title": rule.title_zh if ctx.lang == "zh" else rule.title_en,
                    "clause": clause,
                    "phase": ctx.t(f"phase.{rule.phase.value}"),
                    "check": f"[{rule.check}](checks.md#{rule.check})",
                    "params": _params(rule.params, REGISTRY[rule.check], labels),
                    "severity": ctx.t(f"severity.{rule.severity.value}"),
                    "strict_severity": ctx.t(f"severity.{strict.value}"),
                    "verification": ctx.t(f"verification.{rule.verification.value}"),
                }
            )
        packs.append(
            {
                "name": pack.rulepack,
                "version": pack.version,
                "source": pack.source,
                "source_status": ctx.t(f"source_status.{pack.source_status.value}"),
                "norm": labels["yes"] if pack.norm else labels["no"],
                "sha256": loaded.sha256,
                "rules": rules,
            }
        )
    return env.get_template("rules.md.j2").render(L=labels, packs=packs)


def _calibration() -> dict[str, Any]:
    data = json.loads(CALIBRATION.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise DocsError("calibration/core.json must be an object")
    return data


def threshold_block(metric: str, ctx: Context, env: Environment) -> str:
    labels = ctx.labels["thresholds"]
    origins = _yaml(DATA / "rule_origins.yaml")
    calibration = _calibration()["thresholds"]
    core = builtin_packs()[0].pack
    rows = []
    for rule in core.rules:
        if rule.clause != metric:
            continue
        origin = origins.get(rule.id)
        if not isinstance(origin, dict):
            raise DocsError(f"rule {rule.id} has no origin in docs/_data/rule_origins.yaml")
        kind = str(origin["origin"])
        if kind == "calibrated":
            measured = calibration[rule.id]
            over = labels[f"over_{measured['over']}"]
            text = str(labels["origin_calibrated"]).format(n=measured["n"], over=over, ref=origin["ref"])
        elif kind == "assumption":
            text = str(labels["origin_assumption"]).format(ref=origin["ref"])
        else:
            text = str(labels["origin_with_ref"]).format(origin=labels[f"origin_{kind}"], ref=origin["ref"])
        severity = ctx.t(f"severity.{rule.severity.value}")
        if rule.strict_severity is not None:
            severity += f" (--strict: {ctx.t(f'severity.{rule.strict_severity.value}')})"
        title = rule.title_zh if ctx.lang == "zh" else rule.title_en
        rows.append(
            {
                "rule": f"[{rule.id}](reference/rules.md#{rule.id}) {title}",
                "severity": severity,
                "params": _params(rule.params, REGISTRY[rule.check], ctx.labels["rules"]),
                "origin": text,
            }
        )
    if not rows:
        raise DocsError(f"metrics.md block 'thresholds {metric}' names no core rule")
    return env.get_template("thresholds.md.j2").render(L=labels, rows=rows)


def calibration_block(ctx: Context, env: Environment) -> str:
    rows = [
        {
            "dataset": item["dataset"],
            "version": item["version"],
            "doi": item["doi"],
            "format": item["format"],
            "recordings": item["recordings"],
            "channels": item["M07_channels"],
        }
        for item in sorted(_calibration()["datasets"], key=lambda d: str(d["dataset"]))
    ]
    return env.get_template("calibration.md.j2").render(L=ctx.labels["calibration"], rows=rows)


def installer_block() -> str:
    """Release address and SHA-256 of install_pdf_browser.py of this version (the same bytes as the release
    asset and its SHA256SUMS line; LF in every checkout, .gitattributes)."""
    if not INSTALLER.is_file():
        raise DocsError("tools/install_pdf_browser.py is missing")
    digest = hashlib.sha256(INSTALLER.read_bytes()).hexdigest()
    return "\n".join(["```text", INSTALLER_ADDRESS, f"SHA-256: {digest}", "```", ""])


# --- interpretation questions (RP-08 template, A-92) --------------------------------------------------------
# One entry per clause of a rule pack that can be read in more than one way. The format names no pack, so
# every pack with a norm behind it uses the same file (P7, P8). P6 ships the file empty; entries follow with
# the clause inventory (P8). Texts are own words, never quotes of a norm (A-55); people appear by role only.

_ISO_DATE = re.compile(r"\d{4}-\d{2}-\d{2}", re.ASCII)
# Chinese script in an en field: radicals, CJK symbols and punctuation (the ideographic full stop, the
# corner brackets) up to the CJK compatibility block, extension A, the unified ideographs, the compatibility
# ideographs, vertical and compatibility forms, the half- and full-width forms (full-width comma, colon,
# parentheses) and the supplementary and tertiary ideographic planes (extensions B and later, the
# compatibility supplement).
_HAN = re.compile(
    "[\u2e80-\u2fdf\u3000-\u33ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\ufe10-\ufe1f\ufe30-\ufe4f"
    "\uff00-\uffef\U00020000-\U0003ffff]"
)
# The V-06 guard of tests/unit/test_norm_independence.py (the same patterns; a test there keeps them equal):
# the texts of an entry never name the norm (the field rulepack names the pack), and no generated line
# carries the norm's or the pack's name with a dotted number within 40 characters after it.
NORM_MENTION = re.compile(r"(?i)YY\s*/?\s*T\s*2029|yyt\s*2029")
NORM_CLAUSE = re.compile(r"(?i)(?:YY\s*/?\s*T\s*2029|yyt2029)[^\n]{0,40}?\b\d+(?:\.\d+)+")
QUESTION_STATUSES = ("open", "asked", "answered", "withdrawn")
ASKED_ROLES = ("author", "test_institute", "regulator", "other")
EFFECTS = ("none", "params", "rule_text", "new_rule", "removed_rule")
_STRICT = ConfigDict(extra="forbid", strict=True, frozen=True)


class Reading(BaseModel):
    model_config = _STRICT

    id: str = Field(pattern=r"^[a-z]$")
    en: str = Field(min_length=1, max_length=600)
    zh: str = Field(min_length=1, max_length=600)


class Asked(BaseModel):
    """Whom a question was put to: a role and a date, never a name (NZ-09)."""

    model_config = _STRICT

    role: Literal["author", "test_institute", "regulator", "other"]
    date: dt.date

    @field_validator("date", mode="before")
    @classmethod
    def _date_text(cls, value: Any) -> Any:
        """A YAML date or the same date as quoted text 'YYYY-MM-DD' (as evidence.yaml, A-83)."""
        if isinstance(value, str) and _ISO_DATE.fullmatch(value):
            try:
                return dt.date.fromisoformat(value)
            except ValueError:
                return value
        return value


class Question(BaseModel):
    model_config = _STRICT

    id: str = Field(pattern=r"^IQ-[0-9]{3}$")
    rulepack: str = Field(pattern=r"^[a-z0-9_]+$")
    clause: str = Field(min_length=1, max_length=40)
    rules: list[str] = Field(default_factory=list, max_length=100)
    topic_en: str = Field(min_length=1, max_length=120)
    topic_zh: str = Field(min_length=1, max_length=120)
    question_en: str = Field(min_length=1, max_length=600)
    question_zh: str = Field(min_length=1, max_length=600)
    readings: list[Reading] = Field(min_length=2, max_length=26)
    chosen: str = Field(pattern=r"^[a-z]$")
    rationale_en: str = Field(min_length=1, max_length=600)
    rationale_zh: str = Field(min_length=1, max_length=600)
    status: Literal["open", "asked", "answered", "withdrawn"]
    asked: list[Asked] = Field(default_factory=list, max_length=50)
    answer_en: str | None = Field(default=None, min_length=1, max_length=600)
    answer_zh: str | None = Field(default=None, min_length=1, max_length=600)
    effect: Literal["none", "params", "rule_text", "new_rule", "removed_rule"]
    changed_in: str | None = Field(default=None, min_length=1, max_length=40)


class QuestionsFile(BaseModel):
    model_config = _STRICT

    format_version: Literal[1]
    questions: list[Question] = Field(max_length=1000)


def _texts(item: BaseModel, prefix: str = "") -> list[tuple[str, str]]:
    """Every text field of an entry as (dotted field name, text), readings included."""
    found: list[tuple[str, str]] = []
    for name, value in item:
        if isinstance(value, str):
            found.append((prefix + name, value))
        elif isinstance(value, list):
            for index, element in enumerate(value):
                if isinstance(element, str):
                    found.append((f"{prefix}{name}.{index}", element))
                elif isinstance(element, BaseModel):
                    found += _texts(element, f"{prefix}{name}.{index}.")
    return found


def _forbidden() -> tuple[list[re.Pattern[str]], list[str]]:
    """The A-57 word list of the product (report/wording/forbidden.yaml) and its allowed negations."""
    data = load_yaml(FORBIDDEN.read_text(encoding="utf-8"))
    patterns = [re.compile(p) for lang, group in data.items() if lang != "allowed" for p in group]
    return patterns, [str(phrase) for phrase in data["allowed"]]


def validate_questions(data: object, packs: Mapping[str, Rulepack]) -> QuestionsFile:
    """The questions file, checked against the given packs (the built-in ones in the generator)."""
    try:
        parsed = QuestionsFile.model_validate(data)
    except ValidationError as exc:
        first = exc.errors()[0]
        where = ".".join(str(part) for part in first["loc"])
        raise DocsError(f"interpretation_questions.yaml: {where}: {first['type']}") from None
    patterns, allowed = _forbidden()
    seen: set[str] = set()
    for entry in parsed.questions:
        where = f"interpretation_questions.yaml: {entry.id}"
        if entry.id in seen:
            raise DocsError(f"{where}: duplicate id")
        seen.add(entry.id)
        pack = packs.get(entry.rulepack)
        if pack is None:
            raise DocsError(f"{where}: no built-in rule pack '{entry.rulepack}'")
        if len(set(entry.rules)) != len(entry.rules):
            raise DocsError(f"{where}: duplicate rule id")
        unknown = sorted(set(entry.rules) - {rule.id for rule in pack.rules})
        if unknown:
            raise DocsError(f"{where}: rules not in {entry.rulepack}: {', '.join(unknown)}")
        readings = [reading.id for reading in entry.readings]
        if len(set(readings)) != len(readings):
            raise DocsError(f"{where}: duplicate reading id")
        if entry.chosen not in readings:
            raise DocsError(f"{where}: chosen reading '{entry.chosen}' is not among the readings")
        if entry.status == "answered" and not (entry.answer_en and entry.answer_zh):
            raise DocsError(f"{where}: an answered question needs answer_en and answer_zh")
        if pack.source_status is SourceStatus.PLACEHOLDER and entry.clause != "TBD":
            # a placeholder pack has read no norm text, so a clause number cannot come from it (A-41, V-06)
            raise DocsError(f"{where}: the clause of a placeholder pack is TBD")
        for field, text in _texts(entry):
            if _HAN.search(text) and not (field.endswith("_zh") or field.endswith(".zh")):
                raise DocsError(f"{where}: Chinese text in {field}")
            # the pack and its rule IDs name the pack by design and are checked above
            named = field == "rulepack" or field.startswith("rules.")
            if not named and NORM_MENTION.search(text):
                # own words only (A-55); a mention would also be an unreviewed line of the generated pages
                raise DocsError(f"{where}: {field} names the norm or the pack (V-06)")
            scanned = text
            for phrase in allowed:
                scanned = re.sub(re.escape(phrase), "", scanned, flags=re.IGNORECASE)
            if any(pattern.search(scanned) for pattern in patterns):
                raise DocsError(f"{where}: {field} uses a word of the wording list (A-57)")
    return parsed


def load_questions(path: Path) -> QuestionsFile:
    if not path.is_file():
        raise DocsError(f"{path.name} is missing")
    try:
        data = load_yaml(path.read_text(encoding="utf-8"))
    except ConfigError as exc:
        raise DocsError(f"{path.name}: {exc.message_key}") from None
    return validate_questions(data, {loaded.pack.rulepack: loaded.pack for loaded in builtin_packs()})


def _cell(text: str) -> str:
    """A text in a Markdown table cell: one line, '|' escaped."""
    return " ".join(text.split()).replace("|", "\\|")


def questions_block(ctx: Context, env: Environment) -> str:
    labels = ctx.labels["questions"]
    none = str(ctx.labels["rules"]["none"])
    lang = "zh" if ctx.lang == "zh" else "en"
    rows = []
    for entry in load_questions(QUESTIONS).questions:
        readings = {r.id: _cell(r.zh if lang == "zh" else r.en) for r in entry.readings}
        answer = entry.answer_zh if lang == "zh" else entry.answer_en
        effect = str(labels[f"effect_{entry.effect}"])
        rows.append(
            {
                "id": entry.id,
                "topic": _cell(getattr(entry, f"topic_{lang}")),
                "rulepack": entry.rulepack,
                "clause": _cell(entry.clause),
                "rules": ", ".join(f"[{rule}](reference/rules.md#{rule})" for rule in entry.rules) or none,
                "question": _cell(getattr(entry, f"question_{lang}")),
                "readings": "; ".join(f"({key}) {text}" for key, text in readings.items()),
                "chosen": f"({entry.chosen}) {_cell(getattr(entry, f'rationale_{lang}'))}",
                "status": labels[f"status_{entry.status}"],
                "asked": "; ".join(f"{labels[f'role_{a.role}']} ({a.date.isoformat()})" for a in entry.asked)
                or none,
                "answer": _cell(answer) if answer else none,
                "effect": f"{effect} ({entry.changed_in})" if entry.changed_in else effect,
            }
        )
    block = env.get_template("questions.md.j2").render(L=labels, questions=rows)
    for line in block.splitlines():
        if NORM_CLAUSE.search(line):
            raise DocsError(f"interpretation questions ({ctx.lang}): a line cites a clause number (V-06)")
    return block


def fill_blocks(text: str, ctx: Context, env: Environment) -> str:
    def replace(match: re.Match[str]) -> str:
        name = match.group("name").strip()
        if name.startswith("thresholds "):
            body = threshold_block(name.split(" ", 1)[1], ctx, env)
        elif name == "calibration":
            body = calibration_block(ctx, env)
        elif name == "pdf installer":
            body = installer_block()
        elif name == "interpretation questions":
            body = questions_block(ctx, env)
        else:
            raise DocsError(f"unknown generated block '{name}'")
        return match.group(1) + body + match.group(4)

    return BLOCK.sub(replace, text)


def environment() -> Environment:
    """The template environment of every generated page and block."""
    return Environment(
        loader=FileSystemLoader(str(TEMPLATES)),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
        autoescape=False,  # Markdown, not HTML; values come from NeuroGrid's own tables and packs  # noqa: S701
        trim_blocks=True,
        lstrip_blocks=True,
        comment_start_string="{%#",  # '{#' starts the explicit anchors of the pages ({#M01})
        comment_end_string="#%}",
    )


def generate() -> dict[Path, str]:
    """Every generated file with its expected content."""
    env = environment()
    out: dict[Path, str] = {}
    for lang in LANGUAGES:
        ctx = context(lang)
        folder = DOCS / lang
        out[folder / "reference" / "checks.md"] = render_checks(ctx, env)
        out[folder / "reference" / "rules.md"] = render_rules(ctx, env)
        metrics = folder / "metrics.md"
        if not metrics.is_file():
            raise DocsError(f"{metrics.relative_to(ROOT)} is missing")
        out[metrics] = fill_blocks(metrics.read_text(encoding="utf-8"), ctx, env)
        installation = folder / "installation.md"
        if not installation.is_file():
            raise DocsError(f"{installation.relative_to(ROOT)} is missing")
        text = installation.read_text(encoding="utf-8")
        if "<!-- BEGIN GENERATED pdf installer -->" not in text:
            raise DocsError(f"{installation.relative_to(ROOT)} lacks the generated block 'pdf installer'")
        out[installation] = fill_blocks(text, ctx, env)
        rulepacks = folder / "rulepacks.md"
        if not rulepacks.is_file():
            raise DocsError(f"{rulepacks.relative_to(ROOT)} is missing")
        text = rulepacks.read_text(encoding="utf-8")
        if "<!-- BEGIN GENERATED interpretation questions -->" not in text:
            raise DocsError(
                f"{rulepacks.relative_to(ROOT)} lacks the generated block 'interpretation questions'"
            )
        out[rulepacks] = fill_blocks(text, ctx, env)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        files = generate()
    except DocsError as exc:
        print(f"gen_docs: {exc}", file=sys.stderr)
        return 2
    outdated = []
    for path, text in files.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check:
            outdated.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if outdated:
        print("outdated documentation:", ", ".join(outdated), "- run python tools/gen_docs.py")
        return 1
    print("documentation up to date" if args.check else f"generated {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
